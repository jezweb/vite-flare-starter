// NOTE: renders a plain <div>, not Menu.GroupLabel — Base UI's GroupLabel
// throws outside <Menu.Group>, while every consumer (and radix's Label)
// floats labels directly inside Content. Wrap label + items in
// <DropdownMenuGroup> and switch to GroupLabel if you want the
// aria-labelledby wiring.
function DropdownMenuLabel({
  className,
  inset,
  ...props
}: React.ComponentProps<'div'> & {
  inset?: boolean
}) {
  return (
    <div
      data-slot="dropdown-menu-label"
      data-inset={inset}
      role="presentation"
      className={cn('px-2 py-1.5 text-sm font-medium data-[inset]:pl-8', className)}
      {...props}
    />
  )
}

