#!/usr/bin/env node
/**
 * Generate .jez/artifacts/_index.md from the artifacts themselves.
 *
 * Derived files are generated or don't exist (see
 * ~/.claude/rules/derived-files-generated-not-hand-kept.md) — never
 * hand-edit the index; re-run this after adding/retiring artifacts:
 *
 *   node .jez/scripts/gen-artifacts-index.mjs
 *
 * Metadata is best-effort across the three shapes in the corpus:
 * YAML frontmatter (date/status/supersedes/owner), bold-label headers
 * (**Date**: / **Status**:), and bare files (date from the
 * `-YYYY-MM-DD` filename convention, title from the first H1).
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const artifactsDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'artifacts')

const files = readdirSync(artifactsDir)
  .filter((f) => f.endsWith('.md') && f !== '_index.md')
  .sort()

const rows = files.map((file) => {
  const raw = readFileSync(join(artifactsDir, file), 'utf8')
  const head = raw.slice(0, 3000)
  const meta = { date: '', status: '', supersedes: '', title: '' }

  // 1. YAML frontmatter
  const fm = head.match(/^---\n([\s\S]*?)\n---/)
  if (fm) {
    const get = (k) => fm[1].match(new RegExp(`^${k}:\\s*(.+)$`, 'm'))?.[1].trim() ?? ''
    meta.date = get('date')
    meta.status = get('status')
    meta.supersedes = get('supersedes')
  }

  // 2. Bold-label header style
  if (!meta.date) meta.date = head.match(/\*\*Date\*\*:\s*(\S+)/i)?.[1] ?? ''
  if (!meta.status) meta.status = head.match(/\*\*Status\*\*:\s*(.+)/i)?.[1]?.trim() ?? ''

  // 3. Filename date convention <topic>-YYYY-MM-DD[-suffix].md
  if (!meta.date) meta.date = file.match(/(\d{4}-\d{2}-\d{2})/)?.[1] ?? ''

  meta.title = head.match(/^#\s+(.+)$/m)?.[1]?.trim() ?? file.replace(/\.md$/, '')

  // Normalise noisy status strings to one word + keep the tail short.
  const status = meta.status
    .replace(/[✅🚧⏸️❌*_`]/gu, '')
    .trim()
    .slice(0, 60)

  return { file, ...meta, status }
})

// Newest first — chronology is the main lookup axis.
rows.sort((a, b) => (b.date || '').localeCompare(a.date || '') || a.file.localeCompare(b.file))

const supersededTargets = new Set(rows.map((r) => r.supersedes).filter(Boolean))

const table = rows
  .map((r) => {
    const flags = []
    if (supersededTargets.has(r.file)) flags.push('superseded')
    if (/supersed/i.test(r.status)) flags.push('superseded')
    const note = flags.length ? ` _(${[...new Set(flags)].join(', ')})_` : ''
    return `| ${r.date || '—'} | [${r.title.replace(/\|/g, '\\|').slice(0, 80)}](${r.file}) | ${r.status.replace(/\|/g, '\\|') || '—'}${note} |`
  })
  .join('\n')

const out = `<!-- GENERATED by .jez/scripts/gen-artifacts-index.mjs — do not hand-edit.
     Re-run after adding or retiring artifacts. -->

# Artifacts index

${rows.length} dated artefacts, newest first. Chronology is grep-able from the
filenames (\`<topic>-YYYY-MM-DD.md\`); this table adds title + status at a glance.
The \`design-review-*\` chain pattern: latest is \`active\`, earlier ones carry
\`supersedes:\` pointers and stay for audit.

| Date | Artifact | Status |
|------|----------|--------|
${table}

_Last generated: ${new Date().toISOString().slice(0, 10)}_
`

writeFileSync(join(artifactsDir, '_index.md'), out)
console.log(`wrote _index.md — ${rows.length} artifacts indexed`)
const missingDate = rows.filter((r) => !r.date).length
if (missingDate) console.log(`note: ${missingDate} artifact(s) have no detectable date`)
